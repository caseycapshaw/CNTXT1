"""Regenerate every CONTENT/Skills/<TYPE>/"<TYPE> Index.md" table straight
from each skill note's own frontmatter — nobody hand-writes index rows. Run
via `uv run python SYSTEM/bin/build_skills_indexes.py`.

Columns adapt per TYPE (all keep the | Skill | ... | Notes | shape, Notes =
the note's `summary:`):
- DO / FORMAT: | Skill | Trigger | Notes |
- CHECK:       | Skill | Trigger | Frequency | Notes |
- RULE:        | Skill | Domain | Notes |   (rules default frequency: always)

"* TEMPLATE.md" files and the index files themselves are skipped. A TYPE
folder with no real skills gets no index file (nothing to map).
"""

from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SKILLS_ROOT = REPO_ROOT / "CONTENT" / "Skills"

# TYPE -> extra columns between Skill and Notes, as (Header, frontmatter key).
COLUMNS = {
    "DO": [("Trigger", "trigger")],
    "CHECK": [("Trigger", "trigger"), ("Frequency", "frequency")],
    "FORMAT": [("Trigger", "trigger")],
    "RULE": [("Domain", "domain")],
}

MAX_CELL = 160


def _frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    try:
        data = yaml.safe_load(parts[1])
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}


def _cell(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        s = ", ".join(str(v) for v in value)
    else:
        s = str(value)
    s = s.replace("|", "\\|").replace("\n", " ").strip()
    if len(s) > MAX_CELL:
        s = s[: MAX_CELL - 1].rstrip() + "..."
    return s


def build_type_index(type_dir: Path) -> None:
    type_name = type_dir.name
    index_path = type_dir / f"{type_name} Index.md"
    skills = sorted(
        p for p in type_dir.glob("*.md")
        if not p.name.endswith(" TEMPLATE.md") and p.name != index_path.name
    )
    if not skills:
        return  # nothing to map — don't ship an empty index
    extra = COLUMNS.get(type_name, [("Trigger", "trigger")])
    headers = ["Skill"] + [h for h, _ in extra] + ["Notes"]
    lines = [
        f"# {type_name} skills — index",
        "",
        "Generated by `SYSTEM/bin/build_skills_indexes.py` directly from every",
        "skill's own frontmatter — **do not hand-edit the table below**.",
        "",
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(":--" for _ in headers) + " |",
    ]
    for skill in skills:
        fm = _frontmatter(skill)
        row = (
            [f"[[{skill.stem}]]"]
            + [_cell(fm.get(key)) for _, key in extra]
            + [_cell(fm.get("summary"))]
        )
        lines.append("| " + " | ".join(row) + " |")
    index_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {index_path.relative_to(REPO_ROOT)} ({len(skills)} skills)")


def main() -> None:
    print("Regenerating Skills <TYPE> indexes:")
    for type_name in COLUMNS:
        type_dir = SKILLS_ROOT / type_name
        if type_dir.is_dir():
            build_type_index(type_dir)


if __name__ == "__main__":
    main()
