"""Regenerate each content folder's own index.md (NOT the root index.md — that
is the hand-maintained map and this script never touches it). Each is a small, folder-scoped map
so an agent (or a human) can orient to one folder without loading the whole
vault-wide index. Run via `uv run python SYSTEM/bin/build_directory_indexes.py`.

Two shapes:
- Concepts / Projects / Areas / People / Agents get a frontmatter-driven table,
  wrapped in <!-- dir-index:auto:start --> / <!-- dir-index:auto:end -->
  markers — do not hand-edit inside the markers.
- raw / excalidraw get a plain filename listing (no frontmatter to tabulate).

Files named "* TEMPLATE.md" and the index.md itself are skipped everywhere.

Default is dry-run (print drift, exit 1 if any) — matches build_horizon_serves.py
/ build_contacts_directory.py so lint can call one convention. --write applies.
--check is an alias of dry-run for lint. Each generated block carries a
`_Generated: YYYY-MM-DD_` freshness stamp (ignored by the drift check, so a
stale-by-date file is not flagged — only stale *content* is), so a missed run
is visible in the file itself.
"""

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
_FOLDERS = json.loads((Path(__file__).resolve().parent / "kb-folders.json").read_text())

START = "<!-- dir-index:auto:start -->"
END = "<!-- dir-index:auto:end -->"
STAMP_PREFIX = "_Generated:"
TOOL = "SYSTEM/bin/build_directory_indexes.py"

# folder -> (table columns as (Header, frontmatter key)) — "Note" is implicit.
# Never add 01 Horizons/Goals — its index.md is the H3 horizon note
# (aliases: [goals]), not a generated directory index.
TABLE_TARGETS = {
    _FOLDERS["concepts"]: [
        ("Description", "description"), ("Updated", "updated"),
        ("Status", "status"), ("Tags", "tags"),
    ],
    _FOLDERS["projects"]: [
        ("Description", "description"), ("Status", "status"),
        ("Updated", "updated"), ("Tags", "tags"),
    ],
    _FOLDERS["areas"]: [
        ("Description", "description"), ("Review", "review"),
        ("Reviewed", "reviewed"), ("Tags", "tags"),
    ],
    f"{_FOLDERS['areas']}/Assets": [
        ("Description", "description"), ("Review", "review"),
        ("Reviewed", "reviewed"), ("Tags", "tags"),
    ],
    _FOLDERS["people"]: [
        ("Role", "role"), ("Org", "org"), ("Status", "status"), ("Tags", "tags"),
    ],
    # Agents: top-level role notes only — glob("*.md") is non-recursive, so
    # agent data subfolders (Agents/life-coach/, ...) are never touched.
    "Agents": [
        ("Description", "description"), ("Status", "status"), ("Updated", "updated"),
    ],
}
LISTING_TARGETS = ["raw", "excalidraw"]

MAX_CELL = 80  # keep long descriptions from blowing the table apart


def _notes(folder: Path) -> list[Path]:
    return sorted(
        p for p in folder.glob("*.md")
        if not p.name.endswith(" TEMPLATE.md") and p.name != "index.md"
    )


def _frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    try:
        data = yaml.safe_load(parts[1])
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}


def _cell(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        s = ", ".join(str(v) for v in value)
    else:
        s = str(value)
    s = s.replace("|", "\\|").replace("\n", " ").strip()
    if len(s) > MAX_CELL:
        s = s[: MAX_CELL - 1].rstrip() + "..."
    return s


def _strip_stamp(block: str) -> str:
    return "\n".join(l for l in block.splitlines() if not l.startswith(STAMP_PREFIX))


def _write_or_report(folder: Path, new_lines: list[str], count: int, kind: str, write: bool) -> bool:
    new_text = "\n".join(new_lines) + "\n"
    path = folder / "index.md"
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    changed = (new_text != current) if write else (_strip_stamp(new_text) != _strip_stamp(current))
    if not changed:
        return False
    rel = path.relative_to(REPO_ROOT)
    if write:
        path.write_text(new_text, encoding="utf-8")
        print(f"  wrote {rel} ({count} {kind})")
    else:
        print(f"FAIL {rel}: generated section stale")
    return True


def build_table_index(folder: Path, columns: list[tuple[str, str]], write: bool) -> bool:
    headers = ["Note"] + [h for h, _ in columns]
    lines = [
        START,
        f"# {folder.name} — directory index",
        "",
        "Generated by `SYSTEM/bin/build_directory_indexes.py` directly from every note's",
        "own frontmatter — **do not hand-edit the table below**.",
        "",
        f"{STAMP_PREFIX} {dt.date.today().isoformat()} by {TOOL}.",
        "",
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(":--" for _ in headers) + " |",
    ]
    notes = _notes(folder)
    for note in notes:
        fm = _frontmatter(note)
        row = [f"[[{note.stem}]]"] + [_cell(fm.get(key)) for _, key in columns]
        lines.append("| " + " | ".join(row) + " |")
    if not notes:
        lines.append("| _(none yet)_ " + "| " * len(columns) + "|")
    lines.append(END)
    return _write_or_report(folder, lines, len(notes), "notes", write)


def build_listing_index(folder: Path, write: bool) -> bool:
    lines = [
        START,
        f"# {folder.name} — directory index",
        "",
        "Generated by `SYSTEM/bin/build_directory_indexes.py` — a plain filename",
        "listing (these notes carry no frontmatter to tabulate). **Do not hand-edit.**",
        "",
        f"{STAMP_PREFIX} {dt.date.today().isoformat()} by {TOOL}.",
        "",
    ]
    files = sorted(
        p for p in folder.rglob("*") if p.is_file()
        and p.name != "index.md" and not p.name.startswith(".")
    )
    for f in files:
        lines.append(f"- `{f.relative_to(folder)}`")
    if not files:
        lines.append("_(empty)_")
    lines.append(END)
    return _write_or_report(folder, lines, len(files), "files", write)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="apply writes (default: dry-run)")
    parser.add_argument("--check", action="store_true", help="lint mode: exit 1 on drift")
    args = parser.parse_args()
    write = bool(args.write) and not args.check

    if write:
        print("Regenerating per-directory indexes:")
    any_stale = False
    for rel, columns in TABLE_TARGETS.items():
        folder = REPO_ROOT / rel
        if folder.is_dir():
            any_stale |= build_table_index(folder, columns, write)
    for rel in LISTING_TARGETS:
        folder = REPO_ROOT / rel
        if folder.is_dir():
            any_stale |= build_listing_index(folder, write)

    if not write and any_stale:
        return 1
    if not write:
        print("directory indexes: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
