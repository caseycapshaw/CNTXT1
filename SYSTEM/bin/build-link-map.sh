#!/usr/bin/env bash
# build-link-map.sh — regenerate SYSTEM/link-map.md, the wikilink → file-path index.
# Resolves every [[target]] the KB uses: concept + initiative slugs,
# People names + aliases, Skill slugs + aliases. Run after adding/renaming any
# concept, person, or skill. Idempotent: overwrites SYSTEM/link-map.md.
set -euo pipefail
cd "$(dirname "$0")/../.."   # vault root (SYSTEM/bin -> SYSTEM -> root)
out="SYSTEM/link-map.md"
tmp="$(mktemp)"

emit() { printf '| `[[%s]]` | `%s` |\n' "$1" "$2" >> "$tmp"; }

# Concepts / Initiatives: slug = filename (TEMPLATE files skipped)
collect_simple() {
  local dir="$1"
  for f in "$dir"/*.md; do
    [ -e "$f" ] || continue
    case "$f" in *TEMPLATE*) continue ;; esac
    emit "$(basename "$f" .md)" "$f"
  done
}

# People: canonical name = filename, plus any aliases: [a, b] in frontmatter
collect_with_aliases() {
  local dir="$1"
  for f in "$dir"/*.md; do
    [ -e "$f" ] || continue
    local name; name="$(basename "$f" .md)"
    case "$name" in *TEMPLATE*) continue ;; esac
    emit "$name" "$f"
    local aliases; aliases="$(grep -m1 '^aliases:' "$f" 2>/dev/null | sed -E 's/^aliases:[[:space:]]*\[//; s/\][[:space:]]*$//' || true)"
    [ -z "$aliases" ] && continue
    local IFS=','; for a in $aliases; do
      a="$(printf '%s' "$a" | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//; s/^\"//; s/\"$//')"
      [ -n "$a" ] && emit "$a" "$f"
    done
  done
}

# Skills: canonical name = filename (Imperative Title), plus any aliases: [a, b]
# in frontmatter. Layout: CONTENT/Skills/<TYPE>/<Imperative Title>.md
# (TYPE = DO | CHECK | FORMAT | RULE). TEMPLATE files and generated
# "<TYPE> Index.md" files are skipped.
collect_skills() {
  for f in CONTENT/Skills/*/*.md; do
    [ -e "$f" ] || continue
    case "$f" in *TEMPLATE*|*" Index.md") continue ;; esac
    local name; name="$(basename "$f" .md)"
    emit "$name" "$f"
    local aliases; aliases="$(grep -m1 '^aliases:' "$f" 2>/dev/null | sed -E 's/^aliases:[[:space:]]*\[//; s/\][[:space:]]*$//' || true)"
    [ -z "$aliases" ] && continue
    local IFS=','; for a in $aliases; do
      a="$(printf '%s' "$a" | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//; s/^\"//; s/\"$//')"
      [ -n "$a" ] && emit "$a" "$f"
    done
  done
}

{
  echo "# Link map — wikilink → file path"
  echo
  echo "_Generated by \`SYSTEM/bin/build-link-map.sh\`. Do not hand-edit — regenerate after adding/renaming a concept, initiative, person, or skill._"
  echo
  echo "Resolves every \`[[target]]\` the KB uses (canonical names + registered \`aliases:\`). Use it to jump straight to a file instead of grepping."
  echo
  echo "| Wikilink | Path |"
  echo "| :-- | :-- |"
} > "$tmp"

collect_simple CONTENT/Concepts
collect_simple CONTENT/Initiatives
collect_simple CONTENT/Initiatives/archive
collect_simple CONTENT/Excalidraw
collect_with_aliases CONTENT/People
collect_skills

# sort the table rows (after the 8 header lines), keep header intact
head -8 "$tmp" > "$out"
tail -n +9 "$tmp" | sort -f >> "$out"
rm -f "$tmp"

echo "wrote $out ($(($(wc -l < "$out") - 6)) link targets)"
