#!/usr/bin/env bash
# build-link-map.sh — regenerate SYSTEM/link-map.md, the wikilink → file-path index.
# Resolves every [[target]] the KB uses: concept + project slugs,
# People names + aliases, Skill slugs + aliases. Run after adding/renaming any
# concept, person, or skill. Idempotent: overwrites SYSTEM/link-map.md.
set -euo pipefail
_BIN="$(cd "$(dirname "$0")" && pwd)"
cd "$_BIN/../.."   # vault root (SYSTEM/bin -> SYSTEM -> root)
# shellcheck source=kb-folders.sh
. "$_BIN/kb-folders.sh"   # folder names + extract_aliases()
out="SYSTEM/link-map.md"
tmp="$(mktemp)"

emit() { printf '| `[[%s]]` | `%s` |\n' "$1" "$2" >> "$tmp"; }

# Concepts / Projects: slug = filename (TEMPLATE files skipped), plus any
# aliases: [a, b] in frontmatter (e.g. a renamed note keeps its old slug
# resolvable — renames without aliases silently strand every inbound link).
collect_simple() {
  local dir="$1"
  for f in "$dir"/*.md; do
    [ -e "$f" ] || continue
    case "$f" in *TEMPLATE*|*/index.md) continue ;; esac
    emit "$(basename "$f" .md)" "$f"
    local a
    while IFS= read -r a; do
      [ -n "$a" ] && emit "$a" "$f"
    done < <(extract_aliases "$f")
  done
}

# People: canonical name = filename, plus any aliases: [a, b] in frontmatter
collect_with_aliases() {
  local dir="$1"
  for f in "$dir"/*.md; do
    [ -e "$f" ] || continue
    local name; name="$(basename "$f" .md)"
    case "$name" in *TEMPLATE*|index) continue ;; esac
    emit "$name" "$f"
    local a
    while IFS= read -r a; do
      [ -n "$a" ] && emit "$a" "$f"
    done < <(extract_aliases "$f")
  done
}

# Skills: canonical name = filename (Imperative Title), plus any aliases: [a, b]
# in frontmatter. Layout: Skills/<TYPE>/<Imperative Title>.md
# (TYPE = DO | CHECK | FORMAT | RULE). TEMPLATE files and generated
# "<TYPE> Index.md" files are skipped.
collect_skills() {
  for f in Skills/*/*.md; do
    [ -e "$f" ] || continue
    case "$f" in *TEMPLATE*|*" Index.md"|*/index.md|*/SKILL.md) continue ;; esac
    local name; name="$(basename "$f" .md)"
    emit "$name" "$f"
    local a
    while IFS= read -r a; do
      [ -n "$a" ] && emit "$a" "$f"
    done < <(extract_aliases "$f")
  done
}

{
  echo "# Link map — wikilink → file path"
  echo
  echo "_Generated by \`SYSTEM/bin/build-link-map.sh\`. Do not hand-edit — regenerate after adding/renaming a concept, project, person, or skill._"
  echo
  echo "Resolves every \`[[target]]\` the KB uses (canonical names + registered \`aliases:\`). Use it to jump straight to a file instead of grepping."
  echo
  echo "| Wikilink | Path |"
  echo "| :-- | :-- |"
} > "$tmp"

collect_simple "$KB_CONCEPTS"
collect_simple "$KB_PROJECTS"
collect_simple "$KB_PROJECTS/archive"
collect_simple "$KB_PROJECTS/trails"   # optional trail siblings (cap_overflow.py)
collect_simple "$KB_AREAS"
collect_simple "$KB_AREAS/Assets"
collect_simple "$KB_AREAS/trails"
collect_simple "$KB_HORIZONS"
# H3 outcome notes + the Goals/index.md horizon (registered via aliases: [goals],
# never as [[index]] — that basename is the vault root map).
collect_simple "$KB_HORIZON_GOALS"
if [ -f "$KB_HORIZON_GOALS/index.md" ]; then
  while IFS= read -r a; do
    [ -n "$a" ] && emit "$a" "$KB_HORIZON_GOALS/index.md"
  done < <(extract_aliases "$KB_HORIZON_GOALS/index.md")
fi
collect_simple excalidraw
collect_with_aliases "$KB_PEOPLE"
collect_skills

# System hubs lint already treats as valid wikilink targets — in the map so an
# agent resolving via link-map.md (not grep) finds them.
emit "log" "SYSTEM/log.md"
emit "AGENTS" "AGENTS.md"
emit "SCHEMA" "SYSTEM/SCHEMA.md"
emit "decisions" "SYSTEM/decisions.md"
emit "skill-impact" "SYSTEM/skill-impact.md"
[ -f Actions.md ] && emit "Actions" "Actions.md"

# sort the table rows (after the 8 header lines), keep header intact
head -8 "$tmp" > "$out"
# exact-match dedupe first (sort -u), THEN case-insensitive presentation sort:
# a single `sort -fu` would fold case for the uniqueness test too, silently
# collapsing distinct targets that differ only by case.
tail -n +9 "$tmp" | LC_ALL=C sort -u | LC_ALL=C sort -f >> "$out"
rm -f "$tmp"

# Two different targets claiming the same wikilink key = an ambiguous link.
dups="$(awk -F'`' '/^\| `/ {print $2}' "$out" | sort | uniq -d)"
if [ -n "$dups" ]; then
  echo "FAIL  duplicate wikilink keys in $out:" >&2
  printf '%s\n' "$dups" | sed 's/^/  /' >&2
  echo "wrote $out with duplicates — fix the colliding aliases and regen" >&2
  exit 1
fi

echo "wrote $out ($(($(wc -l < "$out") - 6)) link targets)"
